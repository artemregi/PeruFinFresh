/* ─── Core i18n engine ─── */
window.currentLang = 'es';

window.setLang = function(lang) {
  if (!window.I18N[lang]) lang = 'es';
  window.currentLang = lang;
  localStorage.setItem('lang', lang);

  /* 1. HTML lang attribute */
  document.documentElement.lang = lang;

  /* 2. Simple text replacements via data-i18n */
  var L = window.I18N[lang];
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (L[key] !== undefined) el.textContent = L[key];
  });

  /* 3. Placeholder replacements */
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-ph');
    if (L[key] !== undefined) el.placeholder = L[key];
  });

  /* 4. aria-label replacements */
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-aria');
    if (L[key] !== undefined) el.setAttribute('aria-label', L[key]);
  });

  /* 5. Show/hide language blocks */
  document.querySelectorAll('[data-lang]').forEach(function(el) {
    el.style.display = (el.getAttribute('data-lang') === lang) ? '' : 'none';
  });

  /* 6. Language button states */
  document.querySelectorAll('[data-lang-btn]').forEach(function(btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang-btn') === lang);
  });

  /* 7. Refresh calculator if present */
  if (typeof updateCalc === 'function') updateCalc();
};

/* ─── Auto-init on DOMContentLoaded ─── */
(function() {
  var saved = localStorage.getItem('lang');
  var lang  = (saved === 'es' || saved === 'en') ? saved : 'es';
  window.currentLang = lang;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() { window.setLang(lang); });
  } else {
    window.setLang(lang);
  }
})();
